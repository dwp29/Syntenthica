import gzip
import io
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch
import zipfile
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'build-kit/scripts'))
import audit_chronicle_s31 as a

@unittest.skipUnless(shutil.which('openssl'),'openssl required')
class AuditTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp=tempfile.TemporaryDirectory();cls.addClassCleanup(cls.tmp.cleanup);cls.root=Path(cls.tmp.name)
        key=cls.root/'key.pem';cert=cls.root/'cert.pem';der=cls.root/'cert.der'
        subprocess.run(['openssl','req','-x509','-newkey','rsa:2048','-nodes','-subj','/CN=Build time autogenerated kernel key','-keyout',str(key),'-out',str(cert),'-days','1'],check=True,stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
        subprocess.run(['openssl','x509','-in',str(cert),'-outform','DER','-out',str(der)],check=True)
        cls.cert=der.read_bytes();cls.cfg=b'CONFIG_FIXTURE=y\n'
    def archive(self,name='fixture.zip',duplicate=False):
        data=bytearray(64);data[56:60]=b'ARMd';data+=b'Linux version 4.14.357-fixture\x00KernelSU\x00'+self.cert+b'IKCFG_ST'+gzip.compress(self.cfg,mtime=0)+b'IKCFG_ED'
        image=gzip.compress(data,mtime=0);path=self.root/name
        with zipfile.ZipFile(path,'w') as z:
            for n,v in {'Image.gz':image,'anykernel.sh':b'entry','tools/ak3-core.sh':b'core','tools/magiskboot':b'mb','tools/busybox':b'bb','ksud':b'ksud'}.items():z.writestr(n,v)
            if duplicate:
                import warnings
                with warnings.catch_warnings():
                    warnings.simplefilter('ignore');z.writestr('ksud',b'other')
        return path,image
    def test_cert_and_archive_analysis_with_matching_pins(self):
        path,image=self.archive('a.zip')
        with patch.dict(a.PINS,{'chronicle':(a.sha(path.read_bytes()),a.sha(image))}),patch.object(a,'STOCK_CONFIG',a.sha(self.cfg)):
            report,_=a.inspect(path,'chronicle')
        self.assertEqual(report['autogenerated_cert_sha256'],a.sha(self.cert))
        self.assertIn('not reliable',report['embedded_config_scope']);self.assertEqual(report['kernelsu_literal_count'],1)
    def test_duplicate_entries_and_bad_hash_rejected(self):
        path,image=self.archive('b.zip',duplicate=True)
        with patch.dict(a.PINS,{'chronicle':(a.sha(path.read_bytes()),a.sha(image))}):
            with self.assertRaises(ValueError):a.inspect(path,'chronicle')
        with patch.dict(a.PINS,{'chronicle':('0'*64,a.sha(image))}):
            with self.assertRaises(ValueError):a.inspect(path,'chronicle')
    def test_reject_symlinks(self):
        path,_=self.archive('c.zip');link=self.root/'alias.zip';link.symlink_to(path)
        with self.assertRaises(ValueError):a.inspect(link,'chronicle')
    def test_real_references_if_available(self):
        names=[os.environ.get('S31_CHRONICLE_ZIP'),os.environ.get('S31_CRITICAL_ZIP'),os.environ.get('S31_RELEASE_ZIP')]
        if not all(names):self.skipTest('reference ZIPs not supplied')
        report=a.compare(dict(zip(('chronicle','critical','s31'),map(Path,names))))
        self.assertTrue(report['same_ksud_bytes']);self.assertFalse(report['same_anykernel_core_bytes']);self.assertFalse(report['same_magiskboot_bytes'])
        self.assertEqual(report['builds']['chronicle']['embedded_config_sha256'],a.STOCK_CONFIG)
        self.assertEqual(report['builds']['critical']['embedded_config_sha256'],a.STOCK_CONFIG)
        self.assertNotEqual(report['builds']['chronicle']['autogenerated_cert_sha256'],a.REFERENCE_CERT)
        self.assertNotEqual(report['builds']['critical']['autogenerated_cert_sha256'],a.REFERENCE_CERT)

if __name__=='__main__':unittest.main()
