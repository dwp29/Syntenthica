#!/usr/bin/env python3
"""Compare exact Chronicle, Critical and 3.1 archive inputs offline; no writes to device."""
from __future__ import annotations
import argparse, gzip, hashlib, io, json, re, subprocess, sys, zipfile
from pathlib import Path

PINS={
 'chronicle':('b190fdefca94ff42dbdd88825f9dd89809c94f12c830207bc4dfda52d4058b8f','41e4afb33d2511f1032d4a05e20a3892ca20b7718a8a059138489435cf1ba097'),
 'critical':('d39fbb68359680401a230c5400756d6434b57b5efa8f307c5030245ac1bae8db','59d3722ceb1fce302a79f0680a86226130bc34ef4fc4308aeba91767f1dac754'),
 's31':('1ffe861ceaa2775e4f75bc9f7ecd4b7c56cf9c146f1690eb941c8dd2e5200d4a','650d5f1e9e73788babeb67e5a21a30e565babd059f8cd908c318531464a74287')}
STOCK_CONFIG='8188e2539466a3e6797e98dd704b4b5a8e6439b21c08ba8d2a82b2829a8b190d'
S31_CONFIG='4b53a2cb030e9aa55ff798a3ee5c773c0eb50e56cd36430d2874adcb56fa236d'
REFERENCE_CERT='af3673e410a81247e88bffdb44cac8e642b140cb7caaedc342cdb3170aa5600a'

def sha(data): return hashlib.sha256(data).hexdigest()

def certs(raw):
    marker=b'Build time autogenerated kernel key'; out={}
    for match in re.finditer(re.escape(marker),raw):
        pos=match.start()
        for i in range(max(0,pos-10000),pos):
            if raw[i:i+2]!=b'\x30\x82': continue
            n=int.from_bytes(raw[i+2:i+4],'big')+4
            if n>16000 or not pos<i+n<=len(raw):continue
            value=raw[i:i+n]
            p=subprocess.run(['openssl','x509','-inform','DER','-noout'],input=value,stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
            if p.returncode==0:out[sha(value)]=value
    if len(out)!=1:raise ValueError('expected exactly one parseable autogenerated certificate')
    return out

def inspect(path:Path,label:str) -> tuple[dict,bytes]:
    if path.is_symlink() or not path.is_file() or not 0<path.stat().st_size<=30_000_000:raise ValueError('archive must be a bounded regular file')
    rawzip=path.read_bytes()
    if sha(rawzip)!=PINS[label][0]:raise ValueError(label+' archive hash mismatch')
    with zipfile.ZipFile(io.BytesIO(rawzip)) as z:
        infos=z.infolist();names=[x.filename for x in infos]
        if len(names)!=len(set(names)) or z.testzip():raise ValueError('archive integrity failure')
        fields=('Image.gz','anykernel.sh','tools/ak3-core.sh','tools/magiskboot','tools/busybox','ksud')
        for n in fields:
            if names.count(n)!=1 or z.getinfo(n).file_size>25_000_000:raise ValueError('missing or oversized member '+n)
        parts={n:z.read(n) for n in fields}
    kernel=parts['Image.gz']
    if sha(kernel)!=PINS[label][1]:raise ValueError('kernel hash mismatch')
    with gzip.GzipFile(fileobj=io.BytesIO(kernel)) as f:raw=f.read(100_000_001)
    if len(raw)>100_000_000 or raw[56:60]!=b'ARMd':raise ValueError('invalid raw ARM64 image')
    if raw.count(b'IKCFG_ST')!=1 or raw.count(b'IKCFG_ED')!=1:raise ValueError('invalid config markers')
    a=raw.index(b'IKCFG_ST')+8;b=raw.index(b'IKCFG_ED')
    if b<=a or b-a>4_000_000:raise ValueError('invalid config size')
    cfg=gzip.decompress(raw[a:b]); cfg_hash=sha(cfg)
    if cfg_hash != (S31_CONFIG if label=='s31' else STOCK_CONFIG):raise ValueError('unexpected embedded config')
    found=certs(raw); cert_hash=next(iter(found))
    version=re.findall(rb'Linux version 4\.14\.[^\x00\n]{1,500}',raw)
    if len(version)!=1:raise ValueError('unexpected version records')
    return {'archive_sha256':sha(rawzip),'image_sha256':sha(kernel),'kernel_version':version[0].decode('ascii','replace'),
            'embedded_config_sha256':cfg_hash,
            'embedded_config_scope':'matches generated 3.1 config' if label=='s31' else 'exact stock_defconfig; not reliable build configuration',
            'autogenerated_cert_sha256':cert_hash,'embedded_reference_cert_sha256':REFERENCE_CERT,
            'autogenerated_cert_matches_uploaded_boot_cert':REFERENCE_CERT==cert_hash,
            'member_sha256':{n:sha(parts[n]) for n in fields if n!='Image.gz'},
            'kernelsu_literal_count':raw.count(b'KernelSU')},raw

def compare(paths):
    results={};images={}
    for label,path in paths.items():results[label],images[label]=inspect(path,label)
    # Other certificates and runtime keyrings are outside this comparison.
    return {'builds':results,
            'same_ksud_bytes':len({r['member_sha256']['ksud'] for r in results.values()})==1,
            'same_anykernel_core_bytes':len({r['member_sha256']['tools/ak3-core.sh'] for r in results.values()})==1,
            'same_magiskboot_bytes':len({r['member_sha256']['tools/magiskboot'] for r in results.values()})==1,
            'scope':'Static archive analysis only; does not establish boot, runtime keyring, installed ROM, module signatures or causality.'}

def main():
    p=argparse.ArgumentParser(description=__doc__)
    for n in ('chronicle','critical','s31'):p.add_argument('--'+n,required=True,type=Path)
    a=p.parse_args();print(json.dumps(compare({n:getattr(a,n) for n in ('chronicle','critical','s31')}),indent=2))
if __name__=='__main__':
    try:main()
    except (OSError,ValueError,zipfile.BadZipFile) as e: print('Audit refused: '+str(e),file=sys.stderr);sys.exit(1)
